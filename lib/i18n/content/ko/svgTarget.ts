import type { Change, FullFormat } from "../../../seo/pairLogic";

/**
 * 도착 형식이 SVG인 조합(png-to-svg 등)의 본문. 다른 조합과 달리 "형식 변환"이 아니라
 * 래스터를 도형으로 다시 그리는 트레이싱(추정)이라서, 사실과 다른 문장(픽셀 보존 등)이 나오지 않도록 따로 쓴다.
 * 주의사항은 변환기 화면의 안내(lib/i18n/messages/ko.ts의 svg.notice)와 같은 내용을 유지한다.
 */

const OBJ = "를";
const TO = "로";

/** 사진인 경우가 많은 형식 */
const PHOTO_FORMATS = ["jpg", "heic", "tiff"];

export function svgChanges(from: FullFormat): Change[] {
  const out: Change[] = [
    {
      title: "원본을 그대로 옮기는 것이 아니라 '추정'입니다",
      body: `${from.name}${OBJ} SVG${TO} 바꾸는 이 과정은 이미지 속 색 영역의 윤곽을 찾아 도형으로 다시 그리는 트레이싱입니다. 원본 픽셀을 보존하는 일반적인 변환이 아니어서 ${from.name} 원본과 똑같지 않고, 가장자리가 조금 달라지거나 작은 디테일이 사라질 수 있습니다.`,
    },
  ];

  if (PHOTO_FORMATS.includes(from.id)) {
    out.push({
      title: `${from.name}는 사진인 경우가 많아 SVG 변환에 맞지 않을 수 있습니다`,
      body: `사진은 색이 연속적으로 변해서 도형으로 나누면 결과가 거칠고, 파일이 ${from.name} 원본보다 훨씬 커질 수 있습니다(사진 한 장이 수 MB 이상). 이 사이트는 사진처럼 색이 많은 이미지를 감지하면 결과 화면에 경고를 띄웁니다. 로고나 아이콘이 담긴 ${from.name}라면 괜찮습니다.`,
    });
  } else if (from.id === "ico") {
    out.push({
      title: "작은 아이콘은 윤곽이 각지게 나올 수 있습니다",
      body: `${from.name} 아이콘은 보통 16~256px로 작아서 윤곽 정보가 적습니다. 도형이 각지거나 투박하게 나올 수 있으니, 가능하면 더 큰 원본 이미지에서 SVG로 변환하세요.`,
    });
  } else if (from.id === "gif") {
    out.push({
      title: "GIF의 계단 모양 가장자리는 그대로 따라갑니다",
      body: `GIF는 색이 256개 이하이고 반투명이 없어 가장자리가 계단처럼 보일 수 있습니다. 트레이싱은 보이는 윤곽을 따라가므로 이런 거친 가장자리가 결과에 반영되기도 합니다. 움직이는 GIF는 첫 장면만 사용합니다.`,
    });
  } else {
    out.push({
      title: `색이 적고 경계가 뚜렷한 ${from.name} 이미지에 알맞습니다`,
      body: `로고, 아이콘, 단색 일러스트처럼 색이 적고 경계가 선명한 ${from.name} 이미지는 비교적 잘 변환됩니다. 반대로 사진이나 그라데이션이 많은 이미지는 결과가 거칠어지고 용량이 크게 늘어납니다.`,
    });
  }

  out.push({
    title: "색이 설정한 색 수로 단순화됩니다",
    body: `SVG는 정해진 색 수(2~64색)로 색을 줄여 도형을 만듭니다. ${from.name} 원본의 미묘한 색 차이는 사라지고, 부드러운 그라데이션은 띠 모양으로 나뉠 수 있습니다. 색 수와 디테일 수준은 변환 옵션에서 조절할 수 있고, 로고·아이콘은 4~16색이면 충분한 경우가 많습니다.`,
  });

  out.push({
    title: "글자는 글꼴이 아니라 도형이 됩니다",
    body: `${from.name} 안의 글자는 SVG에서도 글자가 아니라 도형으로 그려집니다. 나중에 글자를 고치거나 검색할 수 없고, 글자가 작거나 흐리면 알아보기 어려울 수 있습니다. 글자를 편집해야 한다면 원본 디자인 파일을 사용하세요.`,
  });

  out.push(
    from.transparency
      ? {
          title: "투명 배경은 유지됩니다",
          body: `${from.name}의 투명한 부분은 SVG에서도 투명으로 남습니다. 배경색으로 채우고 싶다면 옵션의 "투명·여백을 배경색으로 채우기"를 켜세요.`,
        }
      : {
          title: "배경도 하나의 큰 도형으로 들어갑니다",
          body: `${from.name}는 투명 배경이 없어서 배경색이 SVG 안에 큰 도형으로 포함됩니다. 배경이 필요 없다면 변환 후 편집 프로그램에서 해당 도형을 지우거나, 배경이 투명한 원본을 사용하세요.`,
        },
  );

  out.push({
    title: "크기와 용량은 이렇게 달라집니다",
    body: `SVG는 도형이 많을수록 커집니다. 단순한 로고는 ${from.name} 원본보다 작을 수 있지만, 복잡한 이미지는 훨씬 커집니다. 변환 후 결과 화면에서 원본과의 용량을 바로 비교할 수 있고, 원본보다 크면 알려 드립니다. 변환은 한 변 최대 1024px로 줄인 이미지로 하고, SVG의 표시 크기(가로·세로)만 설정한 크기로 적히므로 확대해도 선명합니다.`,
  });

  if (from.id === "tiff") {
    out.push({ title: "여러 페이지 TIFF는 첫 페이지만 변환됩니다", body: "TIFF는 한 파일에 여러 페이지를 담을 수 있습니다. 첫 페이지만 SVG로 만듭니다." });
  }
  if (from.id === "heic") {
    out.push({ title: "라이브 포토의 영상·깊이 정보는 버려집니다", body: "HEIC의 대표 사진 한 장만 SVG로 만듭니다." });
  }
  return out;
}

export function svgWhen(from: FullFormat): string[] {
  const out = [
    `원본 벡터 파일(AI, Figma 등)이 없는 ${from.name} 로고나 아이콘을 확대해도 깨지지 않는 형태로 쓰고 싶을 때`,
    "단순한 그림의 색이나 크기를 웹에서 코드로 바꿔 쓰고 싶을 때",
    "윤곽(벡터)을 입력받는 프로그램(컷팅, 자수, 레이저 가공 등)에 넣을 밑그림이 필요할 때 — 변환 후 정리가 필요할 수 있습니다",
  ];
  if (from.id === "jpg") out.push("저해상도 JPG 로고를 벡터로 다시 만들어 보고 싶을 때 — JPG의 압축 노이즈가 있으면 결과를 정리해야 합니다");
  if (from.id === "ico") out.push("파비콘 ICO를 확대해서 쓸 수 있는 벡터로 만들고 싶을 때 — 작은 아이콘은 윤곽이 거칠 수 있습니다");
  return out;
}

export function svgFaq(from: FullFormat): Array<{ q: string; a: string }> {
  return [
    {
      q: `${from.name}${OBJ} SVG${TO} 바꾸면 화질이 좋아지나요?`,
      a: `아니요. 벡터 변환은 원본에 없는 정보를 만들어 내는 것이 아니라 보이는 색 영역을 도형으로 근사하는 것입니다. ${from.name} 원본이 흐리거나 노이즈가 있으면 결과도 그렇고, 확대해도 선명한 것은 도형의 윤곽뿐입니다.`,
    },
    {
      q: `사진 ${from.name}도 SVG로 바꿀 수 있나요?`,
      a: "변환은 되지만 권하지 않습니다. 사진은 색이 연속적으로 변해서 결과가 거칠고 파일이 수 MB 이상으로 커질 수 있습니다. 사진은 JPG나 WebP로 쓰고, SVG는 로고·아이콘·단색 일러스트에 쓰세요.",
    },
    {
      q: "SVG로 바꾸면 파일이 작아지나요?",
      a: `단순한 ${from.name} 이미지는 작아지기도 하지만 항상 그렇지는 않습니다. 복잡한 이미지는 도형이 많아져 원본보다 훨씬 커질 수 있습니다. 변환 후 결과 화면에서 원본과의 용량을 비교하고, 크면 색 수나 디테일을 낮춰 다시 변환해 보세요.`,
    },
    {
      q: "이미지 속 글자도 SVG에서 편집할 수 있나요?",
      a: "아니요. 글자는 글꼴이 아니라 도형으로 변환되므로 글자를 고치거나 검색할 수 없습니다. 글자를 편집해야 한다면 원본 디자인 파일을 사용하세요.",
    },
    {
      q: "파일이 서버에 업로드되나요?",
      a: `아니요. ${from.name} 파일은 이 브라우저 안에서만 읽고 SVG로 변환되며 서버로 전송되지 않습니다. 촬영 위치 같은 EXIF 정보도 변환 결과에 들어가지 않습니다.`,
    },
  ];
}

/** 리드 문단 2: 일반 변환과 다르다는 점을 먼저 알린다 */
export function svgLeadSecond(from: FullFormat, toSummary: string): string {
  return `SVG는 ${toSummary}입니다. 다만 ${from.name}${OBJ} SVG${TO} 바꾸는 일은 형식만 바꾸는 일반 변환과 달라서, 이미지를 도형으로 다시 그리는 트레이싱(추정)입니다. 로고나 아이콘처럼 단순한 이미지에는 잘 맞지만 사진에는 맞지 않으니 아래의 주의사항을 먼저 확인하세요.`;
}
